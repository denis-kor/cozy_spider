/**
 * Соль кэша игровых ассетов.
 *
 * Ассеты сцен и колод живут под ПОСТОЯННЫМИ именами, и однажды они были
 * розданы браузерам с `Cache-Control: immutable, 30d` — такие записи
 * обычный F5 не перепроверяет вовсе. `?v=` меняет URL, а значит и ключ
 * кэша: все игроки мгновенно получают свежие файлы, а историческое
 * старьё остаётся лежать мёртвым грузом.
 *
 * Сейчас сервер отдаёт webp/json с `no-cache` (ревалидация по ETag),
 * поэтому бампать соль при каждом изменении НЕ нужно — она понадобится
 * снова только если кэш-политика опять кого-то переживёт.
 */
export const ASSET_V = '2'

export function versioned(url: string): string {
  return `${url}?v=${ASSET_V}`
}
