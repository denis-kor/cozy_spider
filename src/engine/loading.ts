/**
 * Счётчик загрузки для бегунка на заставке.
 *
 * `add` объявляет объём работы (когда манифест прочитан и стало известно,
 * сколько картинок ехать), `tick` закрывает одну единицу. Итог никто не
 * знает заранее: сцена и колода читают свои манифесты параллельно, и
 * знаменатель дорастает по ходу — бегунок от этого может чуть отступить
 * назад, но это честнее, чем стоять на месте до конца загрузки.
 */
export interface LoadProgress {
  add(count: number): void
  tick(): void
}
