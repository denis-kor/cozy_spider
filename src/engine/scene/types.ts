/** Описание сцены. Данные, а не код — сцена меняется без пересборки. */

export type LayerEffect = 'water' | 'wind'

export interface LayerSpec {
  id: string
  /** Файл относительно папки сцены. */
  src: string
  /**
   * Коэффициент параллакса. 0 — приклеен к камере (небо),
   * 1 — уезжает на полный размах (передний план).
   */
  parallax: number
  effects?: LayerEffect[]
  /** Маска для эффекта, относительно папки сцены. */
  mask?: string
  /** Множитель амплитуды эффекта для этого слоя. */
  intensity?: number
}


/**
 * Актор — объект сцены со своей жизнью: пламя, котик.
 *
 * От слоя отличается тем, что имеет позицию ВНУТРИ холста, а не занимает
 * его целиком. Координаты задаются в единицах designSize — так их можно
 * снять пипеткой прямо с исходного холста и не пересчитывать при смене
 * разрешения экрана.
 */
export interface ActorSpec {
  id: string
  type: 'flame' | 'cat' | 'radio' | 'plume'
  /** Картинка. Для магнитофона необязательна: есть процедурная заглушка. */
  src?: string
  /** Точка привязки в координатах холста. */
  anchor: [number, number]
  /** Размер в единицах холста. */
  size: [number, number]
  /** С каким слоем едет при параллаксе. */
  parallax: number
  /**
   * Идентификатор слоя, сразу ЗА которым актор встаёт в стопку.
   *
   * Без этого актор оказывается поверх всей сцены: пламя горело бы
   * перед стеклом лампы, а котик плавал бы поверх стола. Не указан —
   * актор кладётся на самый верх.
   */
  after?: string

  /** Пламя: сетка спрайт-листа и скорость. */
  grid?: [number, number]
  fps?: number

  /** Котик: кадр с закрытыми глазами. */
  blinkSrc?: string
  /** Котик: поза «встал и смотрит» — победный финал Камчатки. */
  watchSrc?: string
  /** Котик: поза прыжка — ею он уходит за кадр. */
  leapSrc?: string
  /**
   * Котик: живёт на виду и не ныряет.
   *
   * В пруду он всплывает из воды, в таро выглядывает из-за подоконника —
   * там цикл «спрятался/показался» и есть его жизнь. На Камчатке он просто
   * лежит на доске: прятаться ему некуда и незачем, а без этого флага
   * обычный цикл увёл бы его вниз на четверть минуты и отключил моргание.
   */
  resident?: boolean
  /**
   * Котик: уровень воды в координатах холста — ниже него он обрезан.
   *
   * Нет в манифесте — обреза нет вовсе: маска не строится, отражение
   * выключено. На Камчатке котик лежит на доске у всех на виду, и
   * волнистая кромка с её боковым дрейфом читалась бы как шов по спине.
   */
  waterline?: number
  /** Котик: на сколько единиц холста уходит под воду. */
  diveDepth?: number
  /**
   * Котик: рисовать ли отражение под линией обреза.
   *
   * В пруду под ним вода, и отражение обязательно. В сцене таро он
   * выглядывает из-за каменного подоконника — отражаться не в чем.
   */
  mirror?: boolean
  /**
   * Котик: победное всплытие на финале вместо обычного — высовывается из воды
   * выше обычного, подмигивает и ныряет обратно, после чего появляется плашка.
   * Есть только у пруда (в сцене таро котик за подоконником и без кадра для
   * подмигивания).
   */
  winJump?: boolean
  /**
   * Котик: победный финал «посмотрел и ускакал» — встаёт, разворачивается
   * к сопке, смотрит на извержение и уходит прыжком за правый косяк.
   * Косяк нарисован слоем ПОВЕРХ котика, поэтому уход не требует маски:
   * он просто заезжает за него.
   */
  winRun?: boolean

  /**
   * Столб пепла: где по ширине спрайта проходит ножка, 0..1.
   *
   * Столб растёт от кратера вверх, а не из своего центра, поэтому точка
   * привязки у него внизу — и по горизонтали не посередине картинки, а
   * там, где из горы выходит дым.
   */
  stem?: number

  /**
   * Контактная тень под предметом, долями его собственного размера:
   * `w` — ширина пятна, `a` — непрозрачность в центре, `y` — сдвиг вниз.
   *
   * Вырезанный с белого фона предмет приезжает без тени и читается
   * наклейкой: глаз ищет, чем он касается доски, и не находит. Тень
   * дешевле, чем перерисовывать предмет в перспективе доски.
   */
  shadow?: { w: number; a: number; y: number }

  /**
   * Магнитофон: где на картинке окно кассеты и три клавиши.
   *
   * Прямоугольники в долях спрайта: x, y, ширина, высота от 0 до 1.
   * Заданы данными, а не константами, потому что корпус рисует художник:
   * код не должен диктовать, где на нём окно — он должен уметь его найти.
   */
  window?: [number, number, number, number]
  keys?: [number, number, number, number][]

  /**
   * Приглушение картинки актора, множитель цвета вида 0xd6d6d6.
   *
   * Нужно, когда предмет сгенерирован отдельно от сцены и приходит ярче
   * соседей: он честно нарисован, но не знает, что вокруг вечер и
   * единственный источник света — керосинка. Проще подкрутить множителем,
   * чем переделывать картинку.
   */
  tint?: number
}

/** Подмена слоёв и настроения на время победного торжества. */
export interface WinVariantSpec {
  /** Муд, в который уезжает сцена, пока идёт торжество. */
  mood?: string
  /** Слой -> файл, которым он подменяется. */
  layers?: { id: string; src: string }[]
}

export interface SceneSpec {
  id: string
  /** Размер, под который нарисованы слои. */
  designSize: [number, number]
  /**
   * Запас за краем кадра для параллакса, в долях. Слои обязаны быть шире
   * видимой области, иначе при сдвиге вылезет пустота.
   */
  overscan: number
  /**
   * Куда смещать видимое окно, когда экран шире холста, в долях 0..1.
   *
   * `cover` режет холст по краям, и по умолчанию режет симметрично. Для
   * пруда это верно: интересное у него посередине. Для Камчатки — нет:
   * подоконник с котиком и кассетником нарисован у самого низа кадра, а
   * сверху только небо со звёздами. 0.82 по вертикали означает «жертвуй
   * небом, но покажи доску».
   *
   * Смещение не съедает запас под параллакс целиком — оно ограничено
   * 0.7 слака, иначе на краю размаха камеры вылезла бы пустота.
   */
  focus?: [number, number]
  light: {
    /** Позиция источника в долях кадра. */
    pos: [number, number]
    color: [number, number, number]
    intensity: number
  }
  defaultMood: string
  /**
   * Победный эффект сцены (Celebration). Нет в манифесте — салют:
   * праздник обязан случиться даже у сцены, которая о нём не подумала.
   */
  win?: 'fireworks' | 'starfall' | 'eruption'
  layers: LayerSpec[]
  actors?: ActorSpec[]
  /**
   * Чем сцена меняется на время торжества.
   *
   * Извержение трогает только небо и конус — остальные девять слоёв стоят
   * на месте. Поэтому вместо второй сцены здесь список подмен: те же слои,
   * другие файлы, перекрёстное затухание. Грузятся лениво, в момент победы:
   * держать в памяти два лишних холста 2560x1600 ради события, которое
   * случается раз за партию, телефон не простит.
   */
  winVariant?: WinVariantSpec
  /**
   * План нарезки. Не используется движком — это спека для художника
   * и для скрипта нарезки, лежит рядом с данными намеренно.
   */
  plannedLayers?: LayerSpec[]
}
