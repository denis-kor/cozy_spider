/**
 * Сторож от системного жеста «Назад».
 *
 * На Android с жестовой навигацией (по умолчанию на Pixel, Xiaomi, новых
 * Samsung) свайп от левого ИЛИ правого края — это «Назад». В портрете крайние
 * колонки стоят в ~20 px от края, прямо в этой зоне: игрок тянет карту из
 * правой колонки влево, система забирает касание и уводит страницу назад, а
 * если истории нет — закрывает вкладку.
 *
 * Только Android: на iOS «Назад» — одна левая кромка, игра там проверена и
 * принята как есть, а сторож включил бы кнопку «Назад» Safari и потребовал
 * бы два нажатия, чтобы уйти. iPadOS представляется Маком — тоже мимо.
 *
 * Лечится записью-сторожем в истории: «Назад» снимает её и остаётся на месте.
 * Ставить запись надо из жеста пользователя: Chrome пропускает при «Назад»
 * записи, добавленные без него (history manipulation intervention), поэтому
 * после срабатывания сторож взводится заново на следующем касании, а не прямо
 * в popstate. Двойное «Назад» подряд по-прежнему уводит со страницы — это уже
 * намерение, а не промах пальцем.
 */
const GUARD = 'cozy-back-guard'

export function mountBackGuard(): void {
  // Только сенсорные устройства: на десктопе «Назад» — осознанная кнопка
  // браузера, съедать первое нажатие там незачем.
  if (!window.matchMedia('(pointer: coarse)').matches) return
  if (!/Android/i.test(navigator.userAgent)) return

  // После перезагрузки на записи-стороже («Применить» в лавке, обновить
  // страницу) он уже стоит — второй сверху не кладём, иначе записи копятся.
  let armed = !!(history.state && history.state[GUARD])

  const arm = (): void => {
    if (armed) return
    try {
      history.pushState({ [GUARD]: true }, '')
      armed = true
    } catch {
      // Песочница или запрет истории — живём без сторожа.
    }
  }

  window.addEventListener('popstate', (e) => {
    // Ушли со сторожа на запись под ним — «Назад» поглощён; «Вперёд» на
    // сторожа — он снова на месте.
    armed = !!(e.state && e.state[GUARD])
  })

  // Взвод и перевзвод — на касании: это пользовательская активация. Первое
  // касание — обычно «Играть», то есть сторож стоит раньше первой карты.
  window.addEventListener('pointerdown', arm, true)
}
